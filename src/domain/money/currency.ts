export type Currency = (typeof currencies)[number];

export const persistedCurrencySchema = z
  .strictObject({
    code: z.string(),
    minorUnit: z.number().int().nonnegative(),
    name: z.string(),
  })
  .superRefine((currency, context) => {
    if (!currencies.some((knownCurrency) => currencyMatches(currency, knownCurrency))) {
      context.addIssue({ code: "custom", message: "Use a current ISO 4217 currency." });
    }
  })
  .brand<"Currency">();

export function findCurrency(value: string): Currency | undefined {
  const code = value.normalize("NFC").trim().toUpperCase();
  return currencies.find((currency) => currency.code === code);
}

function currencyMatches(
  first: Readonly<CurrencyFields>,
  second: Readonly<CurrencyFields>,
): boolean {
  return (
    first.code === second.code && first.minorUnit === second.minorUnit && first.name === second.name
  );
}

type CurrencyFields = Readonly<{
  code: string;
  minorUnit: number;
  name: string;
}>;
